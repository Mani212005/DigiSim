"""
Module: report.py
Purpose: Per-class real-instance counts against the data-plan targets (scout report section 3.4), with the
         explicit "real count too low, synthetic-only claim" flag for any class whose real test count is under
         MIN_REAL_TEST_INSTANCES. Rendered as Markdown so it can be committed next to the manifest.
"""

from real_data.config import MIN_REAL_TEST_INSTANCES, SPLITS

# (real train target, real test target) per class from the scout report section 3.4 data plan.
# XNOR has no CGHD class at all; the plan says to report it as synthetic-only rather than invent a number.
TARGETS: dict[str, tuple[int, int]] = {
    "NMOS": (400, 150),
    "PMOS": (400, 150),
    "VDD": (300, 100),
    "GND": (400, 100),
    "INPUT_PORT": (300, 100),
    "OUTPUT_PORT": (300, 100),
    "JUNCTION": (1500, 300),
    "AND": (150, 60),
    "OR": (150, 60),
    "NOT": (150, 60),
    "NAND": (150, 60),
    "NOR": (150, 60),
    "XOR": (150, 60),
    "XNOR": (150, 60),
    "RESISTOR": (200, 50),
    "CAPACITOR": (200, 50),
    "INDUCTOR": (200, 50),
    "BJT_NPN": (200, 50),
    "BJT_PNP": (200, 50),
    "CLOCK": (200, 50),
}

FLAG_TOO_LOW = "real count too low, synthetic-only claim"


def class_flags(counts: dict[str, dict[str, int]], class_names: tuple[str, ...]) -> dict[str, list[str]]:
    """
    Flags per class from the real counts.

    Args:
        counts: split -> class -> instance count.
        class_names: Classes in YOLO id order.
    Returns:
        class -> list of flags. FLAG_TOO_LOW when the test split has fewer than MIN_REAL_TEST_INSTANCES;
        "train n/target" when the real train count is under the plan target.
    """
    flags: dict[str, list[str]] = {}
    for name in class_names:
        found: list[str] = []
        test_n = counts.get("test", {}).get(name, 0)
        if test_n < MIN_REAL_TEST_INSTANCES:
            found.append(FLAG_TOO_LOW)
        train_n = counts.get("train", {}).get(name, 0)
        target = TARGETS.get(name, (0, 0))[0]
        if train_n < target:
            found.append(f"train {train_n}/{target}")
        flags[name] = found
    return flags


def render_report(manifest: dict) -> str:
    """
    Render the real-data report as Markdown.

    Args:
        manifest: The manifest dict (see build.build_manifest).
    Returns:
        Markdown text with image counts per split, the per-class count table and the flags.
    """
    names = tuple(manifest["classes"])
    counts: dict[str, dict[str, int]] = {s: v["class_counts"] for s, v in manifest["splits"].items()}
    flags = class_flags(counts, names)
    lines = [
        "# Real-data report (T4)",
        "",
        "Generated by `cd ml && uv run python -m real_data.build report` from `data_manifest.json`; do not edit by hand.",
        "",
        "## Images per split",
        "",
        "| Split | Images | Sources | Frozen hash (sha256) |",
        "|---|---|---|---|",
    ]
    for split in SPLITS:
        info = manifest["splits"].get(split)
        if info:
            sources = ", ".join(f"{k} {v}" for k, v in sorted(info["sources"].items()))
            lines.append(f"| {split} | {info['images']} | {sources} | `{info['hash'][:16]}...` |")
    drafters = manifest["cghd"]["drafter_splits"]
    lines += [
        "",
        "## CGHD pilot drafters",
        "",
        f"Hugging Face mirror `{manifest['cghd']['hf_repo']}` at revision `{manifest['cghd']['hf_revision']}`. Whole drafters per split, so no drawing is in two splits.",
        "",
        "| Drafter | Split | Images |",
        "|---|---|---:|",
    ]
    for drafter, split in drafters.items():
        n = sum(1 for img in manifest["images"] if img["group"] == drafter)
        lines.append(f"| {drafter} | {split} | {n} |")
    lines += [
        "",
        "## Real instances per class vs the plan (scout report 3.4)",
        "",
        f"Flag `{FLAG_TOO_LOW}` = fewer than {MIN_REAL_TEST_INSTANCES} real test instances: do not make a real-image claim for that class, report it as synthetic-only.",
        "",
        "| Class | train | valid | test | qual | train target | test target | Flags |",
        "|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for name in names:
        row = [counts.get(s, {}).get(name, 0) for s in ("train", "valid", "test", "heldout_qual")]
        target = TARGETS.get(name, (0, 0))
        flag_text = "; ".join(f"**{f}**" if f == FLAG_TOO_LOW else f for f in flags[name]) or "ok"
        lines.append(f"| {name} | {row[0]} | {row[1]} | {row[2]} | {row[3]} | {target[0]} | {target[1]} | {flag_text} |")
    pol = manifest.get("fet_polarity", {})
    lines += [
        "",
        "## Transistor polarity relabelling",
        "",
        f"CGHD `transistor.fet` has no polarity. {pol.get('reference_decisions', 0)} transistors were labelled by eye on one reference photo "
        f"per drawing and propagated to the other photos by position matching. Resulting instances: "
        f"NMOS {pol.get('NMOS', 0)}, PMOS {pol.get('PMOS', 0)}, UNCERTAIN {pol.get('UNCERTAIN', 0)} "
        "(uncertain ones are flagged, kept out of the labels and stored as ignore regions).",
        "",
        "## Ignored regions",
        "",
        "Unmapped CGHD classes and undecided transistors, terminals and supply symbols are not labels. Their boxes are stored as ignore regions "
        "(`data_real/yolo/ignore/`) so the evaluator can mask them instead of counting a correct detection as a false positive.",
        "",
        "| Reason | Boxes |",
        "|---|---:|",
    ]
    for reason, n in sorted(manifest.get("ignored_totals", {}).items()):
        lines.append(f"| {reason} | {n} |")
    lines += [
        "",
        "## Caveats",
        "",
        "- The pilot is 4 drafters, so the real test set is one drafter plus 3 Roboflow images. Gate classes other than AND/OR are far below the plan; "
        "XNOR does not exist in CGHD at all. Fetching more drafters is a one-line change to `real_data/config.py` (`CGHD_PILOT_SPLITS`) and changes the frozen hash.",
        "- `terminal` boxes become INPUT_PORT, OUTPUT_PORT, VDD or GND only when the neighbouring text label says so (explicit in/out/supply names; "
        "component designators like R1 or Q1 never count). Terminals without such a label are ignore regions, not labels.",
        "- CGHD `vss` and `voltage.dc` are not remapped directly: like terminals they become VDD or GND only when the neighbouring text label says so "
        "(vss/gnd/0V is GND, vdd/vcc/+V is VDD), otherwise they are `uncertain_supply` ignore regions; `gnd` maps to GND. Batteries, AC sources, BJTs (no polarity relabel yet), "
        "diodes, op-amps and the other CGHD classes are ignore regions.",
        "- JFET symbols (gate arrow) share the CGHD `transistor.fet` class and are left UNCERTAIN rather than called NMOS.",
        "- The Roboflow and Sampleimages gate labels come from the source (polygons converted to boxes) and our own box labels; their images have unverified provenance.",
        "",
    ]
    return "\n".join(lines)
